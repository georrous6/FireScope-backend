
-- ============================================================
-- 0. EXTENSIONS
-- ============================================================

-- PostGIS must be enabled once per database by a superuser:
--   sudo -u postgres psql -d firescope_db -c "CREATE EXTENSION IF NOT EXISTS postgis;"
-- This line is then a harmless no-op, and a clear reminder if it was skipped.
CREATE EXTENSION IF NOT EXISTS postgis;


-- ============================================================
-- 1. FIRE DETECTIONS TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS fire_detections (

    -- Primary key
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Geographic coordinates
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,

    -- PostGIS geometry (WGS84)
    geom GEOMETRY(Point, 4326)
        GENERATED ALWAYS AS (
            ST_SetSRID(
                ST_MakePoint(longitude, latitude),
                4326
            )
        ) STORED,

    -- FIRMS measurements
    -- MODIS brightness temperatures (K): band 21/22 and band 31.
    brightness DOUBLE PRECISION,
    bright_t31 DOUBLE PRECISION,
    -- VIIRS brightness temperatures (K): I-4 and I-5 channels.
    bright_ti4 DOUBLE PRECISION,
    bright_ti5 DOUBLE PRECISION,
    scan DOUBLE PRECISION,
    track DOUBLE PRECISION,
    frp DOUBLE PRECISION,

    -- Acquisition information
    acq_date DATE NOT NULL,
    acq_time INTEGER NOT NULL,
    acq_datetime TIMESTAMPTZ NOT NULL,

    -- Satellite and sensor information
    satellite TEXT NOT NULL,
    instrument TEXT NOT NULL,
    sensor TEXT NOT NULL,

    -- Detection metadata
    confidence TEXT,
    version TEXT,
    daynight TEXT,
    type INTEGER,

    -- Data provenance
    data_product TEXT NOT NULL,
    source_file TEXT,

    -- Ingestion timestamp
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Constraints
    CONSTRAINT valid_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT valid_longitude
        CHECK (longitude BETWEEN -180 AND 180),

    CONSTRAINT valid_acq_time
        CHECK (
            acq_time BETWEEN 0 AND 2359
            AND acq_time % 100 < 60
        ),

    CONSTRAINT valid_sensor
        CHECK (sensor IN ('MODIS', 'VIIRS')),

    CONSTRAINT valid_data_product
        CHECK (data_product IN ('archive', 'nrt'))

);

-- Upgrade tables created by the earlier version of this schema.
ALTER TABLE fire_detections ADD COLUMN IF NOT EXISTS bright_ti4 DOUBLE PRECISION;
ALTER TABLE fire_detections ADD COLUMN IF NOT EXISTS bright_ti5 DOUBLE PRECISION;


-- ============================================================
-- 2. HARMONIZED CELL MONTH TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS harmonized_cell_month (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    month DATE NOT NULL,
    gx INTEGER NOT NULL,
    gy INTEGER NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    source TEXT NOT NULL,

    detections DOUBLE PRECISION NOT NULL,
    frp_mw DOUBLE PRECISION NOT NULL,

    modis_converted_detections DOUBLE PRECISION NOT NULL,
    modis_converted_frp_mw DOUBLE PRECISION NOT NULL,

    viirs_detections DOUBLE PRECISION NOT NULL,
    viirs_frp_mw DOUBLE PRECISION NOT NULL,

    modis_raw_detections DOUBLE PRECISION NOT NULL,
    modis_raw_frp_mw DOUBLE PRECISION NOT NULL,

    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT harmonized_cell_month_unique_month_cell
        UNIQUE (month, gx, gy),

    CONSTRAINT harmonized_cell_month_valid_latitude
        CHECK (lat BETWEEN -90 AND 90),

    CONSTRAINT harmonized_cell_month_valid_longitude
        CHECK (lon BETWEEN -180 AND 180)

);


-- ============================================================
-- 3. HARMONIZED NATIONAL MONTH TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS harmonized_national_month (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    month DATE NOT NULL UNIQUE,
    source TEXT NOT NULL,

    detections DOUBLE PRECISION NOT NULL,
    frp_mw DOUBLE PRECISION NOT NULL,

    modis_converted_detections DOUBLE PRECISION NOT NULL,
    modis_converted_frp_mw DOUBLE PRECISION NOT NULL,

    viirs_detections DOUBLE PRECISION NOT NULL,
    viirs_frp_mw DOUBLE PRECISION NOT NULL,

    modis_raw_detections DOUBLE PRECISION NOT NULL,
    modis_raw_frp_mw DOUBLE PRECISION NOT NULL,

    detections_p10 DOUBLE PRECISION,
    detections_p90 DOUBLE PRECISION,
    frp_mw_p10 DOUBLE PRECISION,
    frp_mw_p90 DOUBLE PRECISION,

    oos_modis_converted_detections DOUBLE PRECISION,
    oos_modis_converted_frp_mw DOUBLE PRECISION,
    oos_terra_only_converted_detections DOUBLE PRECISION,

    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW()

);


-- ============================================================
-- 4. INDEXES
-- ============================================================

-- Re-ingesting a file replaces its rows (see app/data/ingest.py).
CREATE INDEX IF NOT EXISTS idx_fire_detections_source_file
    ON fire_detections (source_file);

-- Spatial index for geographic queries.
CREATE INDEX IF NOT EXISTS idx_fire_detections_geom
    ON fire_detections
    USING GIST (geom);

-- Time-based queries.
CREATE INDEX IF NOT EXISTS idx_fire_detections_acq_datetime
    ON fire_detections (acq_datetime);

-- Sensor filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_sensor
    ON fire_detections (sensor);

-- Data product filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_data_product
    ON fire_detections (data_product);

-- Combined sensor and time filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_sensor_datetime
    ON fire_detections (sensor, acq_datetime);

CREATE INDEX IF NOT EXISTS idx_harmonized_cell_month_month
    ON harmonized_cell_month (month);

CREATE INDEX IF NOT EXISTS idx_harmonized_cell_month_grid
    ON harmonized_cell_month (gx, gy);

CREATE INDEX IF NOT EXISTS idx_harmonized_national_month_month
    ON harmonized_national_month (month);


-- ============================================================
-- 5. TABLE DESCRIPTION
-- ============================================================

COMMENT ON TABLE fire_detections IS
    'Normalized MODIS and VIIRS active fire detections from NASA FIRMS.';

COMMENT ON COLUMN fire_detections.geom IS
    'WGS84 geographic point generated from longitude and latitude.';

COMMENT ON COLUMN fire_detections.sensor IS
    'Sensor family: MODIS or VIIRS.';

COMMENT ON COLUMN fire_detections.data_product IS
    'FIRMS data product: archive or nrt.';

COMMENT ON COLUMN fire_detections.brightness IS
    'MODIS only: channel 21/22 brightness temperature (K). NULL for VIIRS.';

COMMENT ON COLUMN fire_detections.bright_t31 IS
    'MODIS only: channel 31 brightness temperature (K). NULL for VIIRS.';

COMMENT ON COLUMN fire_detections.bright_ti4 IS
    'VIIRS only: I-4 channel brightness temperature (K). NULL for MODIS.';

COMMENT ON COLUMN fire_detections.bright_ti5 IS
    'VIIRS only: I-5 channel brightness temperature (K). NULL for MODIS.';

COMMENT ON COLUMN fire_detections.confidence IS
    'MODIS: 0-100. VIIRS: l (low), n (nominal), h (high).';

COMMENT ON TABLE harmonized_cell_month IS
    'Harmonized monthly fire activity by 0.25 degree cell in VIIRS-equivalent units.';

COMMENT ON TABLE harmonized_national_month IS
    'Harmonized monthly national fire activity totals in VIIRS-equivalent units.';
