
-- ============================================================
-- 1. FIRE DETECTIONS TABLE
-- ============================================================

CREATE TABLE IF NOT EXISTS fire_detections (

    -- Primary key
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Geographic coordinates
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,

    -- PostGIS geometry (WGS84)
    geom GEOMETRY(Point, 4326)
        GENERATED ALWAYS AS (
            ST_SetSRID(
                ST_MakePoint(longitude, latitude),
                4326
            )
        ) STORED,

    -- FIRMS measurements
    brightness DOUBLE PRECISION,
    scan DOUBLE PRECISION,
    track DOUBLE PRECISION,
    bright_t31 DOUBLE PRECISION,
    frp DOUBLE PRECISION,

    -- Acquisition information
    acq_date DATE NOT NULL,
    acq_time INTEGER NOT NULL,
    acq_datetime TIMESTAMPTZ NOT NULL,

    -- Satellite and sensor information
    satellite TEXT NOT NULL,
    instrument TEXT NOT NULL,
    sensor TEXT NOT NULL,

    -- Detection metadata
    confidence TEXT,
    version TEXT,
    daynight TEXT,
    type INTEGER,

    -- Data provenance
    data_product TEXT NOT NULL,
    source_file TEXT,

    -- Ingestion timestamp
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Constraints
    CONSTRAINT valid_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT valid_longitude
        CHECK (longitude BETWEEN -180 AND 180),

    CONSTRAINT valid_acq_time
        CHECK (
            acq_time BETWEEN 0 AND 2359
            AND acq_time % 100 < 60
        ),

    CONSTRAINT valid_sensor
        CHECK (sensor IN ('MODIS', 'VIIRS')),

    CONSTRAINT valid_data_product
        CHECK (data_product IN ('archive', 'nrt'))

);


-- ============================================================
-- 2. INDEXES
-- ============================================================

-- Spatial index for geographic queries.
CREATE INDEX IF NOT EXISTS idx_fire_detections_geom
    ON fire_detections
    USING GIST (geom);

-- Time-based queries.
CREATE INDEX IF NOT EXISTS idx_fire_detections_acq_datetime
    ON fire_detections (acq_datetime);

-- Sensor filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_sensor
    ON fire_detections (sensor);

-- Data product filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_data_product
    ON fire_detections (data_product);

-- Combined sensor and time filtering.
CREATE INDEX IF NOT EXISTS idx_fire_detections_sensor_datetime
    ON fire_detections (sensor, acq_datetime);


-- ============================================================
-- 3. TABLE DESCRIPTION
-- ============================================================

COMMENT ON TABLE fire_detections IS
    'Normalized MODIS and VIIRS active fire detections from NASA FIRMS.';

COMMENT ON COLUMN fire_detections.geom IS
    'WGS84 geographic point generated from longitude and latitude.';

COMMENT ON COLUMN fire_detections.sensor IS
    'Sensor family: MODIS or VIIRS.';

COMMENT ON COLUMN fire_detections.data_product IS
    'FIRMS data product: archive or nrt.';
